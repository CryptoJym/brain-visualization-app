import {execFileSync,spawnSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync,cpSync,readdirSync,statSync,existsSync} from 'node:fs';
import {dirname,resolve,relative} from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const out=resolve(root,'.local-evidence/hero-editions'),snapshot=resolve(out,'release-candidate');
const executable='/Users/utlyze/Projects/freely-sweet/node_modules/.bin/wrangler';
const env={...process.env,CLOUDFLARE_AUTH_USE_KEYRING:'true',WRANGLER_SEND_METRICS:'false'};
const expected='6fc5170e-fbea-44f1-bfaf-07e0b6d7fec0';
const git=(...args)=>execFileSync('git',['-C',root,...args],{encoding:'utf8'}).trim();
assert.equal(git('status','--porcelain','--','src','worker','wrangler.jsonc','public'),'','Runtime files must be committed.');
assert.equal(git('diff','43ceccb','--name-only','--','worker','wrangler.jsonc','src/data/neurohero'),'','Portrait backend and hero inference data must remain unchanged.');
const proof=JSON.parse(readFileSync(resolve(out,'final-checks/receipt.json')));assert.equal(proof.ok,true);assert.ok(proof.passed>=281);
const unit=readFileSync(resolve(out,'unit-final.log'),'utf8');assert.match(unit,/# pass 253/);assert.match(unit,/# fail 0/);
const native=()=>JSON.parse(execFileSync(executable,['deployments','list','--config',resolve(root,'wrangler.jsonc'),'--json'],{env,encoding:'utf8'})).at(-1);
assert.deepEqual(native().versions,[{version_id:expected,percentage:100}],'Production changed; reconcile before publishing.');
assert.ok(proof.suites.some(s=>s.name==='hero-editions'&&s.passed>=35));
assert.ok(proof.suites.some(s=>s.name==='edition-webkit'&&s.passed>=12));
assert.equal(existsSync(snapshot),false,'Release candidate exists; inspect it before any retry.');
mkdirSync(snapshot);
for(const name of ['src','worker','dist'])cpSync(resolve(root,name),resolve(snapshot,name),{recursive:true});
cpSync(resolve(root,'wrangler.jsonc'),resolve(snapshot,'wrangler.jsonc'));
function paths(dir){return readdirSync(dir).flatMap(n=>{const path=resolve(dir,n);return statSync(path).isDirectory()?paths(path):[path];});}
const hashes=Object.fromEntries(paths(snapshot).map(path=>[relative(snapshot,path),createHash('sha256').update(readFileSync(path)).digest('hex')]));
const sourceCommit=git('rev-parse','HEAD');
writeFileSync(resolve(out,'release-manifest.json'),JSON.stringify({sourceCommit,previousVersion:expected,files:hashes},null,2));
assert.deepEqual(native().versions,[{version_id:expected,percentage:100}],'Production changed during preparation.');
for(const [path,hash] of Object.entries(hashes))assert.equal(createHash('sha256').update(readFileSync(resolve(snapshot,path))).digest('hex'),hash);
console.log('Native predecessor and frozen candidate verified. Deploying the accepted release.');
const result=spawnSync(executable,['deploy','--config',resolve(snapshot,'wrangler.jsonc')],{cwd:snapshot,env,encoding:'utf8',timeout:120000});
writeFileSync(resolve(out,'deployment.log'),(result.stdout||'')+(result.stderr||''));
console.log(result.stdout||'',result.stderr||'');
assert.equal(result.status,0,'Inspect the native deployment before retrying.');
const deployed=native();
writeFileSync(resolve(out,'deployment.json'),JSON.stringify({status:'deployed-awaiting-live-verification',sourceCommit,previousVersion:expected,deployment:deployed},null,2));
console.log(JSON.stringify(deployed,null,2));
